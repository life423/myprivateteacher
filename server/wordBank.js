// The starting Phoneme Pop word bank. The server copies any of these the database lacks into its
// words collection when it starts; words already there are left as they are, so later edits stick.
//
// phonemes: the sounds in order, each one a sound with a picture (src/data/phonemeSymbols.js).
// display: the word as shown. Vowels carry a breve (short, ă) or a macron (long, ā); silent
// letters stay plain; [brackets] mark letters that team up to make one sound (they render
// underlined). Strip the marks and brackets and you get the word back (wordBank.test.js checks).

